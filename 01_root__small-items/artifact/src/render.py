def read_csv(name):
    with open(os.path.join(RESULTS, name), newline="") as f:
        return list(csv.DictReader(f))


def write(name, text):
    os.makedirs(GENERATED, exist_ok=True)
    with open(os.path.join(GENERATED, name), "w") as f:
        f.write(text)


def macro_name(key):
    s = re.sub(r"[^A-Za-z0-9]", " ", key)
    parts = []
    for w in s.split():
        w = "".join(DIG[c] if c.isdigit() else c for c in w)
        parts.append(w[0].upper() + w[1:])
    return "".join(parts)


def pct(x, d=1):
    return f"{100*x:.{d}f}"


def ci_pct(ci):
    """'[0.64, 0.79]' (proportions) -> '[64, 79]' (percent)."""
    lo, hi = [float(x) for x in ci.strip("[]").split(",")]
    return f"[{100*lo:.0f}, {100*hi:.0f}]"


def fmt_p(p):
    if p < 0.001:
        return "$<$0.001"
    return f"{p:.3f}" if p >= 0.01 else f"{p:.2g}"


def macros(S):
    lines = []
    for k, v in sorted(S.items()):
        if isinstance(v, (dict, list)):
            continue
        name = macro_name(k)
        if isinstance(v, bool):
            continue
        if isinstance(v, int):
            lines.append(f"\\newcommand{{\\S{name}}}{{{v}}}")
        elif isinstance(v, float):
            if k.endswith("_p") or "_p_" in k:
                lines.append(f"\\newcommand{{\\S{name}}}{{{fmt_p(v)}}}")
            elif "dprime" in k:
                lines.append(f"\\newcommand{{\\S{name}}}{{{v:.2f}}}")
            elif k.startswith("mean_"):
                lines.append(f"\\newcommand{{\\S{name}}}{{{v:.1f}}}")
            else:
                lines.append(f"\\newcommand{{\\S{name}}}{{{v:.3f}}}")
                lines.append(f"\\newcommand{{\\P{name}}}{{{pct(v)}}}")
                lines.append(f"\\newcommand{{\\Pz{name}}}{{{pct(v, 0)}}}")
        elif isinstance(v, str) and k != "note":
            lines.append(f"\\newcommand{{\\S{name}}}{{{v}}}")
    lines.append(f"\\newcommand{{\\GenModel}}{{{SHORT[GEN_MODEL]}}}")
    lines.append(f"\\newcommand{{\\StrongModel}}{{{SHORT[STRONG_MODEL]}}}")
    lines.append(f"\\newcommand{{\\JudgeA}}{{{SHORT[JUDGE_MODELS[0]]}}}")
    lines.append(f"\\newcommand{{\\JudgeB}}{{{SHORT[JUDGE_MODELS[1]]}}}")
    lines.append(f"\\newcommand{{\\ProbeB}}{{{SHORT[PROBE_MODELS[1]]}}}")
    write("macros.tex", "% generated by artifact/src/render.py -- do not edit\n" + "\n".join(lines) + "\n")


def _pc(S, k, d=0):
    v = S.get(k)
    return "--" if v is None or v != v else pct(v, d)


def tab_corpus(S):
    rows = read_csv("corpus_summary.csv")
    ops = {r["op"]: r for r in read_csv("by_operator.csv") if r["generator"] == GEN_MODEL}
    body = []
    for r in rows:
        if r["op"] == "ALL":
            body.append("\\midrule")
            o = {"wit_u": S["wit_gen_raw_a"], "wit_gs": S["wit_gen_strict_b"],
                 "pred_u": S.get("pred_gen_exact_a"), "pred_g": S.get("pred_gen_exact_b")}
            lab = "\\textbf{all}"
        else:
            o = {k: (float(v) if v not in ("", None) else None) for k, v in ops.get(r["op"], {}).items()
                 if k in ("wit_u", "wit_gs", "pred_u", "pred_g")}
            lab = r["label"]
        f = lambda k: "--" if o.get(k) is None else pct(o[k], 0)   # noqa: E731
        body.append(f"{lab} & {r['n']} ({r['n_he']}/{r['n_mbpp']}) & {r['median_diff_frac']} & {r['raise_mostly']} & "
                    f"{f('wit_u')}/{f('wit_gs')} & {f('pred_u')}/{f('pred_g')} \\\\")
    tex = ("\\begin{table}[t]\n\\centering\\footnotesize\n"
           # caption kept to <=4 lines; column details (default-argument never fired, G* = copies as errors) are in the text
           "\\caption{Corpus by operator ($n$: HE+/MBPP+). diff: median share of inputs whose result changes; "
           "rais.: raising on most inputs; witness/affected: " + SHORT[GEN_MODEL] + " error (\\%), U/G$^{*}$, U/G.}\n\\label{tab:corpus}\n\\setlength{\\tabcolsep}{3pt}\n"
           "\\begin{tabular}{@{}lrcrcc@{}}\n\\toprule\nOperator & $n$ & diff & rais. & witness & affected \\\\\n\\midrule\n"
           + "\n".join(body) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    write("tab_corpus.tex", tex)


def tab_h0(S):
    def line(lab, key):
        if f"{key}_a" not in S:
            return f"\\quad {lab} & -- & -- & -- & -- \\\\"
        a, b, d = S[f"{key}_a"], S[f"{key}_b"], S[f"{key}_d"]
        holm = S.get(f"{key}_p_holm")
        ptxt = fmt_p(holm) if holm is not None else fmt_p(S[f"{key}_p"]) + "$^{\\dagger}$"
        return (f"\\quad {lab} & {pct(a)} & {pct(b)} & {pct(d)} [{pct(S[key + '_d_lo'], 0)}, {pct(S[key + '_d_hi'], 0)}]"
                f" & {ptxt} \\\\")
    body = []
    for gk, g in (("gen", GEN_MODEL), ("strong", STRONG_MODEL)):
        n = S.get(f"wit_{gk}_n", "?")
        npred = S.get(f"pred_{gk}_n", "?")
        body.append(f"\\multicolumn{{5}}{{@{{}}l}}{{\\emph{{{SHORT[g]}}} (witness $n$={n}; affected $n$={npred})}} \\\\")
        body.append(line("witness error", f"wit_{gk}_raw"))
        body.append(line("witness, copies = error", f"wit_{gk}_strict"))
        body.append(line("\\ \\ malformed not counted", f"wit_{gk}_strictreason"))
        body.append(line("affected-set error", f"pred_{gk}_exact"))
        if f"pred_{gk}_u_exact_err_scorable" in S:
            body.append(f"\\quad \\ \\ scorable only ({S[f'pred_{gk}_u_unscorable_n']}/{S[f'pred_{gk}_g_unscorable_n']} unscor.) & "
                        f"{pct(S[f'pred_{gk}_u_exact_err_scorable'])} & {pct(S[f'pred_{gk}_g_exact_err_scorable'])} & & \\\\")
            body.append(f"\\quad affected bal.\\ acc.\\ (const.\\ {pct(S[f'pred_{gk}_trivial_bal'])}) & {pct(S[f'pred_{gk}_balacc_u'])} & "
                        f"{pct(S[f'pred_{gk}_balacc_g'])} & {pct(S[f'pred_{gk}_balacc_d'])} & {fmt_p(S[f'pred_{gk}_balacc_p'])}$^{{\\dagger}}$ \\\\")
            body.append(f"\\quad affected F1 (const.\\ {pct(S[f'pred_{gk}_trivial_f1'])}) & {pct(S[f'pred_{gk}_u_f1'])} & "
                        f"{pct(S[f'pred_{gk}_g_f1'])} & & \\\\")
    tex = ("\\begin{table}[t]\n\\centering\\footnotesize\n"
           "\\caption{H0: ungrounded (U) vs.\\ grounded (G), paired by function, in \\%; $\\Delta$=U$-$G, 95\\% bootstrap CI; "
           # caption kept to <=4 lines; metric definitions (affected-set error, bal. acc., F1, const., genuine n) are in the text
           "$p$: exact McNemar, Holm-adjusted ($^{\\dagger}$: unadjusted, secondary; bal.\\ acc.: Wilcoxon).}\n"
           "\\label{tab:h0}\n\\setlength{\\tabcolsep}{3pt}\n"
           "\\begin{tabular}{@{}lrrcr@{}}\n\\toprule\nMeasure & U & G & $\\Delta$ & $p$ \\\\\n\\midrule\n"
           + "\n".join(body) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    write("tab_h0.tex", tex)


def tab_probe(S):
    KL = {"DESC": "descriptive ($P$)", "CF": "counterfactual", "CF_CTRL": "counterf., unaffected $x$",
          "DESC_MUT": "descriptive ($P_m$ shown)"}
    cols = [("p14s", "he"), ("p14s", "mb"), ("p7s", "he"), ("p7s", "mb")]
    body = []
    for k in ("DESC", "CF", "CF_CTRL", "DESC_MUT"):
        cells = [_pc(S, f"probe_{m}_{k}_{src}") for m, src in cols]
        body.append(f"{KL[k]} & " + " & ".join(cells) + " \\\\")
    body.append("\\midrule")
    body.append("\\multicolumn{5}{@{}l}{\\emph{Ablation: initial materials (docstring, comments and name kept)}} \\\\")
    for k in ("DESC", "DESC_MUT"):
        cells = [_pc(S, f"probe_{m.replace('s', 'd')}_{k}_{src}") for m, src in cols]
        body.append(f"{KL[k]} & " + " & ".join(cells) + " \\\\")
    tex = ("\\begin{table}[t]\n\\centering\\footnotesize\n"
           "\\caption{Model-side probe (NOT human data): accuracy (\\%) by benchmark; main rows without docstrings, "
           "comments and entry name. HE+ $n$="
           + str(S.get("probe_p14s_DESC_he_n", "?")) + ", MBPP+ $n$=" + str(S.get("probe_p14s_DESC_mb_n", "?")) +
           " (CF on an unaffected input: $n$=" + str(S.get("probe_p14s_CF_CTRL_he_n", "?")) + "/"
           + str(S.get("probe_p14s_CF_CTRL_mb_n", "?")) + ").}\n\\label{tab:probe}\n\\setlength{\\tabcolsep}{3pt}\n"
           "\\begin{tabular}{@{}lcccc@{}}\n\\toprule\n & \\multicolumn{2}{c}{" + SHORT[PROBE_MODELS[0]] + "} & "
           "\\multicolumn{2}{c}{" + SHORT[PROBE_MODELS[1]] + "} \\\\\nQuestion & HE+ & MBPP+ & HE+ & MBPP+ \\\\\n\\midrule\n"
           + "\n".join(body) + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    write("tab_probe.tex", tex)


def fig_strata(S):
    strata = [("narrow", "$<$10\\%"), ("mid", "10--50\\%"), ("broad", "$\\geq$50\\%")]
    series = []
    styles = [("gen", "ungrounded", "fill=white,draw=black"),
              ("gen", "grounded", "fill=gray!55,draw=black"),
              ("strong", "ungrounded", "fill=white,draw=black,postaction={pattern=north east lines}"),
              ("strong", "grounded", "fill=gray!55,draw=black,postaction={pattern=crosshatch}")]
    for gk, cond, sty in styles:
        coords = []
        for st, lab in strata:
            v = S.get(f"pred_{gk}_{cond}_exact_err_{st}")
            if v is not None and v == v:
                coords.append(f"({st},{100*v:.1f})")
        if coords:
            name = SHORT[GEN_MODEL if gk == "gen" else STRONG_MODEL]
            series.append(f"\\addplot[ybar,{sty}] coordinates {{{' '.join(coords)}}};\n"
                          f"\\addlegendentry{{{name}, {cond[0].upper()}}}")
    ticks = ",".join(f"{{{lab} ($n$={S.get('n_stratum_' + st, '?')})}}" for st, lab in strata)
    tex = ("\\begin{figure}[t]\n\\centering\n\\begin{tikzpicture}\n"
           "\\begin{axis}[width=\\columnwidth,height=4.6cm,ybar=1pt,bar width=7pt,ymin=0,ymax=118,\n"
           "  ylabel={affected-set error (\\%)},ylabel style={font=\\footnotesize},\n"
           "  symbolic x coords={narrow,mid,broad},xtick=data,xticklabels={" + ticks + "},\n"
           "  x tick label style={font=\\scriptsize},y tick label style={font=\\scriptsize},enlarge x limits=0.22,\n"
           "  nodes near coords,nodes near coords style={font=\\tiny,rotate=90,anchor=west,/pgf/number format/.cd,fixed,precision=1,fixed zerofill},\n"
           "  legend style={at={(0.5,1.02)},anchor=south,legend columns=2,font=\\scriptsize,draw=none,"
           "/tikz/every even column/.append style={column sep=4pt}},\n"
           "  legend image code/.code={\\draw[#1] (0cm,-0.08cm) rectangle (0.3cm,0.12cm);},\n"
           "  ymajorgrids,grid style={dashed,gray!30}]\n"
           + "\n".join(series) +
           "\n\\end{axis}\n\\end{tikzpicture}\n"
           "\\caption{Affected-set error by breadth of the executed difference (fraction of test inputs whose result "
           "changes); tick labels give " + SHORT[GEN_MODEL] + "'s $n$. " + SHORT[STRONG_MODEL] + " bars cover its "
           + str(S.get("pred_strong_n", "?")) + "-function subset ($n$=" + str(S.get("pred_strong_n_narrow", "?")) + "/"
           + str(S.get("pred_strong_n_mid", "?")) + "/" + str(S.get("pred_strong_n_broad", "?")) +
           "). Values printed on bars (0.0 = no error).}\n\\label{fig:strata}\n\\end{figure}\n")
    write("fig_strata.tex", tex)


def main():
    S = json.load(open(os.path.join(RESULTS, "summary.json")))
    macros(S)
    for old in ("tab_articulation.tex", "fig_operator.tex"):
        if os.path.exists(os.path.join(GENERATED, old)):
            os.remove(os.path.join(GENERATED, old))
    tab_corpus(S)
    tab_h0(S)
    tab_probe(S)
    fig_strata(S)
    print("rendered ->", GENERATED, sorted(os.listdir(GENERATED)))


if __name__ == "__main__":
    main()
